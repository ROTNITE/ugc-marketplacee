const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (typeof window === "undefined") {
      return "en";
    }
    const saved = window.localStorage.getItem("ugc-locale");
    const browser = navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
    return saved === "ru" || saved === "en" ? saved : browser;
  });

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem("ugc-locale", locale);
    document.cookie = `ugc-locale=${locale}; path=/; max-age=31536000; SameSite=Lax`;
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale(localeValue) {
        setLocaleState(localeValue);
      },
      t(key, values) {
        const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
        return Object.entries(values ?? {}).reduce(
          (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
          template
        );
      },
      formatDate(value) {
        return new Intl.DateTimeFormat(locale === "ru" ? "ru-RU" : "en-US", {
          dateStyle: "medium",
          timeStyle: "short"
        }).format(value instanceof Date ? value : new Date(value));
      },
      formatMoney(cents) {
        return new Intl.NumberFormat(locale === "ru" ? "ru-RU" : "en-US", {
          currency: "RUB",
          maximumFractionDigits: 2,
          style: "currency"
        }).format(cents / 100);
      },
      formatNumber(value) {
        return new Intl.NumberFormat(locale === "ru" ? "ru-RU" : "en-US").format(value);
      }
    }),
    [locale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function LanguageToggle() {
  const { locale, setLocale, t } = useI18n();
  const nextLocale = locale === "ru" ? "en" : "ru";

  return (
    <button
      aria-label={t("app.language")}
      className="language-toggle"
      onClick={() => setLocale(nextLocale)}
      type="button"
    >
      {t("app.toggleLanguage")}
    </button>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error("useI18n must be used within I18nProvider.");
  }

  return context;
}
